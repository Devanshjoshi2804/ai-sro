"""Writes the extension's copy of the page recorder, secrets already baked in.

MV3 content scripts are static files -- there is no injection-time hook the
way Steel's Playwright adapter has (`add_init_script`, substituting
`__SECRET_WORDS__` fresh on every page). This runs the exact same
substitution once, from the exact same `_recorder_script()`, so
`SECRET_TOKENS` stays the one list either side reads from -- never a second
copy hand-kept under `new-chrome-extension/` that drifts from this one.

Run with `make gen-recorder`. Regenerate whenever recorder.js or the secret
word list changes; the generated file is committed so "load unpacked" needs
no build step.
"""

from __future__ import annotations

from pathlib import Path

from sro.infrastructure.steel.capture import _recorder_script

_OUT = (
    Path(__file__).resolve().parents[5]
    / "new-chrome-extension"
    / "src"
    / "content"
    / "recorder.generated.js"
)

_HEADER = (
    "// GENERATED by `make gen-recorder` from backend/src/sro/infrastructure/steel/recorder.js.\n"
    "// Do not edit this file directly -- edit that one and regenerate.\n\n"
)


def main() -> None:
    _OUT.write_text(_HEADER + _recorder_script(), encoding="utf-8")
    print(f"wrote {_OUT}")  # noqa: T201


if __name__ == "__main__":
    main()
